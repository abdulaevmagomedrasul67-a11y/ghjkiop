   Текст должен быть содержательным, насыщенным конкретикой, без воды и тавтологии, полностью заполняя заданный лимит знаков.
""".trimIndent()

    fun buildSectionPrompt(
        meta: WorkMeta,
        section: WorkSection,
        relaySummary: String?
    ): String {
        val targetChars = section.targetCharacters
        val minChars = section.minCharacters
        val maxChars = section.maxCharacters

        val contextBlock = if (!relaySummary.isNullOrBlank()) {
            """
=== КРАТКИЙ КОНТЕКСТ ПРЕДЫДУЩИХ РАЗДЕЛОВ (ДЛЯ СОБЛЮДЕНИЯ ЛОГИЧЕСКОЙ СВЯЗНОСТИ) ===
$relaySummary
==================================================================================
""".trimIndent()
        } else {
            ""
        }

        val sectionSpecificInstructions = when (section.type) {
            SectionType.INTRODUCTION -> """
Напишите раздел «ВВЕДЕНИЕ» строго по ГОСТ 7.32-2017:
- Актуальность темы исследования «${meta.topic}».
- Степень научной разработанности проблемы (с упоминанием ключевых отечественных и зарубежных ученых).
- Цель и задачи исследования (4-5 конкретных исследовательских задач).
- Объект и предмет исследования.
- Теоретико-методологическая база исследования (методы индукции, дедукции, сравнительного и статистического анализа).
- Научная новизна и практическая значимость работы.
- Структура работы.
""".trimIndent()

            SectionType.CONCLUSION -> """
Напишите раздел «ЗАКЛЮЧЕНИЕ»:
- Развернутые выводы по каждой из поставленных во введении задач.
- Обобщение теоретических и практических результатов, полученных в главах.
- Практические рекомендации по использованию полученных результатов.
- Перспективы дальнейших научных исследований в данной области.
- НЕ ИСПОЛЬЗУЙТЕ фразу «В заключение» или «Таким образом»! Начинайте непосредственно с формулировки научных итогов.
""".trimIndent()

            SectionType.BIBLIOGRAPHY -> """
Составьте «СПИСОК ИСПОЛЬЗОВАННЫХ ИСТОЧНИКОВ» строго по ГОСТ Р 7.0.100-2018:
- Нумерованный список от 25 до 40 актуальных академических источников (нормативно-правовые акты РФ при наличии, монографии, статьи из журналов ВАК/Scopus за последние 3-5 лет, статистические сборники).
- Полное библиографическое описание (авторы, название, издательство, год, страницы / URL и дата обращения).
""".trimIndent()

            SectionType.SUBSECTION, SectionType.CHAPTER -> """
Напишите подробный, аналитический текст подраздела «${section.title}»:
- Глубокое раскрытие сущности заявленного вопроса темы «${meta.topic}».
- Применение табличных данных, классификаций, примеров и нормативной базы.
- Цитирование и отсылки к научным источникам в квадратных скобках вида [3, с. 115] или [12].
- Логический академический переход к следующему вопросу.
""".trimIndent()

            else -> "Напишите содержательный академический текст для раздела «${section.title}»."
        }

        return """
ТЕМА РАБОТЫ: «${meta.topic}»
ТИП РАБОТЫ: ${meta.type.titleRu}
ЦЕЛЕВОЙ ОБЪЕМ РАБОТЫ: ${meta.targetPages} страниц

РАЗДЕЛ ДЛЯ ГЕНЕРАЦИИ: «${section.title}»
ТРЕБУЕМЫЙ ОБЪЕМ ДАННОГО РАЗДЕЛА: от $minChars до $maxChars символов с пробелами (цель: $targetChars символов).

$contextBlock

СПЕЦИФИКАЦИЯ РАЗДЕЛА:
$sectionSpecificInstructions

ФОРМАТ ВЫВОДА:
- Выводите ТОЛЬКО текст самого раздела без приветствий, мета-комментариев и оформления в тройные обратные кавычки.
- Заголовок раздела «${section.title}» укажите первой строкой.
- Текст должен быть разбит на логические абзацы с красной строки.
- Строго соблюдайте объем (не менее $minChars знаков!).
""".trimIndent()
    }

    fun buildSummaryPrompt(sectionTitle: String, sectionContent: String): String {
        val truncatedContent = sectionContent.take(4000)
        return """
Вы — научный редактор. Перед вами текст только что написанного раздела «$sectionTitle»:
\"\"\"
$truncatedContent
\"\"\"

Сформулируйте ровно ТРИ (3) плотных, емких академических предложения, обобщающих:
1) Ключевой теоретический тезис или предметный результат этого раздела;
2) Основные выявленные факторы, методы или эмпирические показатели;
3) Логический вектор, необходимый для продолжения в следующей главе.

ТРЕБОВАНИЯ:
- Ровно 3 предложения на русском языке.
- Предельная фактологическая плотность, без вводных фраз вроде «В этом разделе автор рассмотрел...».
- Пишите сугубо содержательные выводы.
""".trimIndent()
    }

    /**
     * Постобработка и очистка текста от шаблонных клише ИИ для гарантии прохождения антиплагиата.
     */
    fun sanitizeAndHumanize(text: String): String {
        var result = text.trim()

        // Убираем маркерные клише (с поддержкой кириллицы в любом регистре)
        result = result.replace(Regex("[Вв]ажно\\s+[Оо]тметить,?\\s*"), "")
        result = result.replace(Regex("[Нн]еобходимо\\s+[Оо]тметить,?\\s*"), "")
        result = result.replace(Regex("[Сс]ледует\\s+[Пп]одчеркнуть,?\\s*"), "")
        result = result.replace(Regex("[Нн]ельзя\\s+[Нн]е\\s+[Уу]помянуть,?\\s*"), "")
        result = result.replace(Regex("[Тт]аким\\s+[Оо]бразом,?\\s*"), "Следовательно, ")
        result = result.replace(Regex("[Пп]одводя\\s+[Ии]тог[и]?,?\\s*"), "Обобщая установленные факты, ")
        result = result.replace(Regex("[Вв]\\s+[Зз]аключение\\s+[Сс]ледует\\s+[Сс]казать,?\\s*"), "")
        result = result.replace(Regex("[Вв]\\s+[Зз]аключение,?\\s*"), "")
        result = result.replace(Regex("[Вв]\\s+[Сс]овременном\\s+[Мм]ире,?\\s*"), "В современных реалиях ")
        result = result.replace(Regex("[Кк]ак\\s+[Бб]ыло\\s+[Сс]казано\\s+[Вв]ыше,?\\s*"), "")

        // Исправление двойных пробелов после вырезания
        result = result.replace(Regex("[ ]{2,}"), " ")
        return result
    }
